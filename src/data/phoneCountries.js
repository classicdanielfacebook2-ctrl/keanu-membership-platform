export const allowedPhoneCountries = internationalCountries
  .filter((country) => country.region !== "Africa" || approvedAfricanCountries.has(country.iso))
  .sort((a, b) => a.name.localeCompare(b.name));

export const getCountryFlag = (iso = "") =>
  iso
    .toUpperCase()
    .replace(/./g, (character) => String.fromCodePoint(127397 + character.charCodeAt(0)));

export const isAllowedPhoneCountry = (iso = "") => allowedPhoneCountries.some((country) => country.iso === iso);

export const getAllowedPhoneCountry = (iso = "US") =>
  allowedPhoneCountries.find((country) => country.iso === iso) || allowedPhoneCountries.find((country) => country.iso === "US");

export const isAllowedPhoneNumber = (phone = "") => {
  const normalized = String(phone).replace(/[^\d+]/g, "");
  const country = internationalCountries
    .filter((item) => normalized.startsWith(item.callingCode))
    .sort((a, b) => b.callingCode.length - a.callingCode.length)[0];

  if (!country) return false;
  return country.region !== "Africa" || approvedAfricanCountries.has(country.iso);
};
